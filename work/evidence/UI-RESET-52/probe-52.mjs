/** 200% text variant: settings-only mutation, checksum recomputed. */
function largeText(raw) {
  const env = JSON.parse(raw);
  env.payload.settings = { ...env.payload.settings, textScale: 2 };
  return JSON.stringify({
    schemaVersion: env.schemaVersion,
    checksum: checksum(JSON.stringify(env.payload)),
    payload: env.payload,
  });
}
