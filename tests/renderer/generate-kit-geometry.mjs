/**
 * RW3D T10 (#137): regenerate src/game/renderer/kitGeometry.ts from the
 * authoring source docs/vision/assets/kit.json (read-only input).
 *
 * The renderer embeds the geometry so it never reads docs at runtime (same
 * precedent as src/game/world/kit.ts). The parity test
 * tests/renderer/assembly-kit-parity.test.ts fails on any drift, so this
 * script is the only sanctioned way to change the embedded table.
 *
 * Usage: node tests/renderer/generate-kit-geometry.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const kit = JSON.parse(readFileSync(resolve(root, "docs/vision/assets/kit.json"), "utf8"));

// The eight placeable assets, exactly the WorldAssetId union in world/kit.ts.
const PLACEABLE = [
  "warehouse",
  "depot",
  "sorter",
  "furnace",
  "generator",
  "crane",
  "turret",
  "wall_gate",
];

const num = (n) => JSON.stringify(n);
const vec3 = (v) => `[${v.map(num).join(", ")}]`;

const lines = [];
lines.push(`/**`);
lines.push(` * RW3D T10 (#137): embedded kit geometry for the mechanical assembly view.`);
lines.push(` *`);
lines.push(` * GENERATED by tests/renderer/generate-kit-geometry.mjs from`);
lines.push(` * docs/vision/assets/kit.json — do not edit by hand. The parity test`);
lines.push(` * tests/renderer/assembly-kit-parity.test.ts guards drift against the`);
lines.push(` * authoring source. Pure data: no THREE, no DOM, no clock.`);
lines.push(` */`);
lines.push(`import type { WorldAssetId } from "../world/kit";`);
lines.push(``);
lines.push(`export type KitMaterialToken =`);
const tokens = Object.keys(kit.palette);
tokens.forEach((t, i) => {
  lines.push(`  | ${JSON.stringify(t)}${i === tokens.length - 1 ? ";" : ""}`);
});
lines.push(``);
lines.push(`export interface KitPartGeometry {`);
lines.push(`  readonly name: string;`);
lines.push(`  /** Kit group this part hangs from ("root" = the building pivot). */`);
lines.push(`  readonly parent: string;`);
lines.push(`  readonly center: readonly [number, number, number];`);
lines.push(`  readonly size: readonly [number, number, number];`);
lines.push(`  readonly material: KitMaterialToken;`);
lines.push(`}`);
lines.push(``);
lines.push(`export interface KitGroupGeometry {`);
lines.push(`  readonly name: string;`);
lines.push(`  readonly parent: string;`);
lines.push(`  readonly position: readonly [number, number, number];`);
lines.push(`}`);
lines.push(``);
lines.push(`export interface KitAssetGeometry {`);
lines.push(`  readonly id: WorldAssetId;`);
lines.push(`  readonly footprint: readonly [number, number];`);
lines.push(`  readonly groups: readonly KitGroupGeometry[];`);
lines.push(`  readonly parts: readonly KitPartGeometry[];`);
lines.push(`}`);
lines.push(``);
lines.push(`/** Palette tokens transcribed verbatim from kit.json. */`);
lines.push(`export const KIT_PALETTE: Readonly<Record<KitMaterialToken, string>> = {`);
for (const t of tokens) lines.push(`  ${JSON.stringify(t)}: ${JSON.stringify(kit.palette[t])},`);
lines.push(`};`);
lines.push(``);
lines.push(`export const KIT_GEOMETRY: Readonly<Record<WorldAssetId, KitAssetGeometry>> = {`);
for (const id of PLACEABLE) {
  const a = kit.assets.find((x) => x.id === id);
  if (a === undefined) throw new Error(`kit.json missing asset ${id}`);
  lines.push(`  ${JSON.stringify(id)}: {`);
  lines.push(`    id: ${JSON.stringify(id)},`);
  lines.push(`    footprint: ${vec3(a.footprint).replace(/]$/, "]")},`);
  lines.push(`    groups: [`);
  for (const g of a.groups) {
    lines.push(`      { name: ${JSON.stringify(g.name)}, parent: ${JSON.stringify(g.parent)}, position: ${vec3(g.position)} },`);
  }
  lines.push(`    ],`);
  lines.push(`    parts: [`);
  for (const p of a.parts) {
    lines.push(`      { name: ${JSON.stringify(p.name)}, parent: ${JSON.stringify(p.parent)}, center: ${vec3(p.center)}, size: ${vec3(p.size)}, material: ${JSON.stringify(p.material)} },`);
  }
  lines.push(`    ],`);
  lines.push(`  },`);
}
lines.push(`};`);
lines.push(``);

const out = resolve(root, "src/game/renderer/kitGeometry.ts");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`wrote ${out} (${PLACEABLE.length} assets, ${tokens.length} palette tokens)`);
